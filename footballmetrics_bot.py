class FootballVisualizer:
    def _base_layout(self, title: str) -> dict:
        return dict(
            title=dict(text=title, font=dict(size=20, color=TEXT)),
            paper_bgcolor=BG,
            plot_bgcolor=BG,
            font=dict(color=TEXT, size=13),
            margin=dict(l=120, r=40, t=80, b=40),
        )

    # ------------------------------------------------------------------ #
    def create_top_players_chart(
        self,
        data: pd.DataFrame,
        stat: str,
        stat_label: str,
        competition: Optional[str],
        position: Optional[str],
        output_path: str,
    ) -> str:
        data = data.iloc[::-1]  # so #1 ends up on top of a horizontal bar
        labels = [f"{p} ({s})" for p, s in zip(data["player"], data["squad"])]

        fig = go.Figure(
            go.Bar(
                x=data[stat],
                y=labels,
                orientation="h",
                marker=dict(
                    color=data[stat],
                    colorscale=[[0, PRIMARY], [1, ACCENT]],
                ),
                text=data[stat].round(2),
                textposition="outside",
            )
        )

        subtitle_bits = [competition or "Все лиги"]
        if position:
            subtitle_bits.append(position)
        title = f"Топ-{len(data)} по «{stat_label}»<br><sup>{' · '.join(subtitle_bits)}</sup>"

        fig.update_layout(**self._base_layout(title))
        fig.update_xaxes(gridcolor=GRID, zerolinecolor=GRID)
        fig.update_yaxes(gridcolor=GRID)
        fig.update_layout(height=120 + 40 * len(data), width=900)

        fig.write_image(output_path, scale=2)
        return output_path

    # ------------------------------------------------------------------ #
    def create_radar_chart(
        self,
        player1: pd.Series,
        player2: pd.Series,
        position_group: str,
        output_path: str,
    ) -> str:
        metrics = RADAR_PRESETS.get(position_group, RADAR_PRESETS["MF"])
        cols = [c for c, _ in metrics]
        labels = [lbl for _, lbl in metrics]

        # Normalize each axis 0-1 against the max of the two players (avoids
        # one huge outlier axis squashing everything else).
        vals1, vals2 = [], []
        for c in cols:
            v1 = float(player1.get(c) or 0)
            v2 = float(player2.get(c) or 0)
            m = max(v1, v2, 1e-6)
            vals1.append(v1 / m)
            vals2.append(v2 / m)

        fig = go.Figure()
        fig.add_trace(
            go.Scatterpolar(
                r=vals1 + vals1[:1],
                theta=labels + labels[:1],
                fill="toself",
                name=f"{player1['player']} ({player1['squad']})",
                line=dict(color=PRIMARY),
            )
        )
        fig.add_trace(
            go.Scatterpolar(
                r=vals2 + vals2[:1],
                theta=labels + labels[:1],
                fill="toself",
                name=f"{player2['player']} ({player2['squad']})",
                line=dict(color=ACCENT),
            )
        )

        fig.write_image(output_path, scale=2)
        return output_path

    # ------------------------------------------------------------------ #
    def create_scatter_chart(
        self,
        data: pd.DataFrame,
        x_stat: str,
        y_stat: str,
        x_label: str,
        y_label: str,
        competition: Optional[str],
        position: Optional[str],
        output_path: str,
    ) -> str:
        labels = [f"{p} ({s})" for p, s in zip(data["player"], data["squad"])]

        fig = go.Figure(
            go.Scatter(
                x=data[x_stat],
                y=data[y_stat],
                mode="markers+text",
                text=data["player"],
                textposition="top center",
                textfont=dict(size=9, color=TEXT),
                marker=dict(
                    size=12,
                    color=data[x_stat],
                    colorscale=[[0, PRIMARY], [1, ACCENT]],
                    line=dict(width=1, color=BG),
                ),
                hovertext=labels,
                hoverinfo="text",
            )
        )

        # Mean reference lines help spot over/under performers at a glance.
        fig.add_hline(y=data[y_stat].mean(), line_dash="dot", line_color=GRID)
        fig.add_vline(x=data[x_stat].mean(), line_dash="dot", line_color=GRID)

        subtitle_bits = [competition or "Все лиги"]
        if position:
            subtitle_bits.append(position)
        title = f"{x_label} vs {y_label}<br><sup>{' · '.join(subtitle_bits)}</sup>"

        fig.update_layout(**self._base_layout(title))
        fig.update_xaxes(title=x_label, gridcolor=GRID, zerolinecolor=GRID)
        fig.update_yaxes(title=y_label, gridcolor=GRID, zerolinecolor=GRID)
        fig.update_layout(width=900, height=650, showlegend=False)

        fig.write_image(output_path, scale=2)
        return output_path

    # ------------------------------------------------------------------ #
    def create_age_trend_chart(
        self, data: pd.DataFrame, stat_label: str, subtitle: str, output_path: str
    ) -> str:
        fig = go.Figure(
            go.Scatter(
                x=data["age"],
                y=data["avg_value"],
                mode="lines+markers",
                line=dict(color=PRIMARY, width=3),
                marker=dict(size=8, color=ACCENT),
                hovertext=[f"n={c} игроков" for c in data["count"]],
                hoverinfo="x+y+text",
            )
        )
        fig.update_layout(
            **self._base_layout(f"«{stat_label}» по возрасту<br><sup>{subtitle}</sup>")
        )
        fig.update_xaxes(title="Возраст", gridcolor=GRID, dtick=1)
        fig.update_yaxes(title=stat_label, gridcolor=GRID)
        fig.update_layout(width=900, height=550)

        fig.write_image(output_path, scale=2)
        return output_path

    # ------------------------------------------------------------------ #
    def create_league_trend_chart(
        self, data: pd.DataFrame, stat_label: str, subtitle: str, output_path: str
    ) -> str:
        data = data.sort_values("avg_value")
        fig = go.Figure(
            go.Bar(
                x=data["avg_value"],
                y=data["league"],
                orientation="h",
                marker=dict(
                    color=data["avg_value"],
                    colorscale=[[0, PRIMARY], [1, ACCENT]],
                ),
                text=data["avg_value"].round(2),
                textposition="outside",
                hovertext=[f"n={c} игроков" for c in data["count"]],
            )
        )
        fig.update_layout(
            **self._base_layout(f"«{stat_label}» по лигам<br><sup>{subtitle}</sup>")
        )
        fig.update_xaxes(title=stat_label, gridcolor=GRID)
        fig.update_yaxes(gridcolor=GRID)
        fig.update_layout(width=900, height=400)

        fig.write_image(output_path, scale=2)
        return output_path

