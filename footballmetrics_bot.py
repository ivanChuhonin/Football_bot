async def on_stat(update: Update, context: ContextTypes.DEFAULT_TYPE) -> int:
    query = update.callback_query
    await query.answer()
    stat = query.data.split(":", 1)[1]

    competition = context.user_data.get("competition")
    position = context.user_data.get("position")

    await query.edit_message_text("📊 Считаю...")

    top_players = data_processor.get_top_players_by_stat(
        stat=stat, competition=competition, position=position, top_n=10
    )

    if top_players.empty:
        await query.edit_message_text(
            "Нет данных под эти фильтры. Попробуйте другую комбинацию.",
            reply_markup=again_keyboard(),
        )
        return MAIN_MENU

    output_path = f"temp_chart_{update.effective_user.id}.png"
    visualizer.create_top_players_chart(
        data=top_players,
        stat=stat,
        stat_label=data_processor.get_stat_description(stat),
        competition=competition,
        position=position,
        output_path=output_path,
    )

    caption_lines = [
        f"📈 Топ-{len(top_players)} по «{data_processor.get_stat_description(stat)}»",
        f"🏆 {competition or 'Все лиги'}" + (f" · {position}" if position else ""),
        "",
    ]
    for i, row in top_players.iterrows():
        val = row[stat]
        val_str = f"{val:.2f}" if isinstance(val, float) else str(val)
        caption_lines.append(f"{i + 1}. {row['player']} ({row['squad']}): {val_str}")

    with open(output_path, "rb") as photo:
        await context.bot.send_photo(
            chat_id=update.effective_chat.id,
            photo=photo,
            caption="\n".join(caption_lines),
        )
    if os.path.exists(output_path):
        os.remove(output_path)

    await context.bot.send_message(
        chat_id=update.effective_chat.id,
        text="Хотите ещё что-нибудь посмотреть?",
        reply_markup=again_keyboard(),
    )
    return MAIN_MENU


