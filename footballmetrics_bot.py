class FootballDataProcessor:
    """Loads and serves the cleaned football statistics dataframe."""

    def __init__(self, csv_path: str, min_nineties_default: float = 3.0):
        self.csv_path = csv_path
        self.min_nineties_default = min_nineties_default
        self.df = self._load_and_clean(csv_path)

    # ------------------------------------------------------------------ #
    # Loading / cleaning
    # ------------------------------------------------------------------ #
    def _load_and_clean(self, csv_path: str) -> pd.DataFrame:
        raw = pd.read_csv(csv_path)

        frames = []
        rename_map = {**_BASE_COLUMNS}
        frames.append(raw[list(_BASE_COLUMNS.keys())].rename(columns=_BASE_COLUMNS))

        for block, suffix in (
            (_KEEPER_COLUMNS, ""),
            (_SHOOTING_COLUMNS, "_stats_shooting"),
            (_PLAYING_TIME_COLUMNS, "_stats_playing_time"),
            (_MISC_COLUMNS, "_stats_misc"),
        ):
            cols = {}
            for src, dst in block.items():
                candidate = src if src in raw.columns else f"{src}{suffix}"
                if candidate in raw.columns:
                    cols[candidate] = dst
                else:
                    logger.warning("Column %s not found in source CSV", src)
            frames.append(raw[list(cols.keys())].rename(columns=cols))

        df = pd.concat(frames, axis=1)

        # Normalize primary position (players can have "MF,FW" — take first).
        df["pos_primary"] = df["pos"].str.split(",").str[0].str.strip()

        # Clean competition names (drop the leading country code, e.g. "eng ").
        df["comp_clean"] = df["comp"].str.replace(
            r"^[a-z]{2,3}\s+", "", regex=True
        )

        # Numeric coercion for anything that should be numeric.
        numeric_cols = [c for c in df.columns if c not in (
            "player", "nation", "pos", "squad", "comp", "pos_primary", "comp_clean"
        )]
        for c in numeric_cols:
            df[c] = pd.to_numeric(df[c], errors="coerce")

        df = self._add_per90_metrics(df)
        df = df.dropna(subset=["player"]).reset_index(drop=True)
        logger.info("Loaded %d player rows from %s", len(df), csv_path)
        return df

    @staticmethod
    def _add_per90_metrics(df: pd.DataFrame) -> pd.DataFrame:
        safe_90s = df["nineties"].replace(0, pd.NA)
        df["gls_90"] = (df["gls"] / safe_90s).round(2)
        df["ast_90"] = (df["ast"] / safe_90s).round(2)
        df["g_plus_a_90"] = (df["g_plus_a"] / safe_90s).round(2)
        df["int_90"] = (df["int_"] / safe_90s).round(2)
        df["tklw_90"] = (df["tklw"] / safe_90s).round(2)
        df["crs_90"] = (df["crs"] / safe_90s).round(2)
        return df

    # ------------------------------------------------------------------ #
    # Menu helpers
    # ------------------------------------------------------------------ #
    def get_available_competitions(self) -> list[str]:
        return sorted(self.df["comp_clean"].dropna().unique().tolist())

    def get_competition_display_name(self, comp: str) -> str:
        return comp

    def get_available_statistics(self) -> list[str]:
        return MENU_STATS

    def get_stat_description(self, stat: str) -> str:
        return STAT_DESCRIPTIONS.get(stat, stat)

    def get_position_groups(self) -> dict[str, str]:
        return POSITION_GROUPS

    # ------------------------------------------------------------------ #
    # Queries
