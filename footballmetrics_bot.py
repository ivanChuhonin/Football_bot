def build_application(token: str) -> Application:
    application = Application.builder().token(token).build()

    conv_handler = ConversationHandler(
        entry_points=[CommandHandler("start", start)],
        states={
            MAIN_MENU: [
                CallbackQueryHandler(on_main_menu, pattern="^menu:"),
                CallbackQueryHandler(on_continue, pattern="^cont:"),
            ],
            CHOOSE_COMPETITION: [
                CallbackQueryHandler(on_competition, pattern="^comp:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            CHOOSE_POSITION: [
                CallbackQueryHandler(on_position, pattern="^pos:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            CHOOSE_STAT: [
                CallbackQueryHandler(on_stat_page, pattern="^statpage:"),
                CallbackQueryHandler(on_stat, pattern="^stat:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
                CallbackQueryHandler(noop, pattern="^noop$"),
            ],
            CMP_SEARCH_1: [
                MessageHandler(filters.TEXT & ~filters.COMMAND, on_search_player1)
            ],
            CMP_PICK_1: [
                CallbackQueryHandler(on_pick_player1, pattern="^p1:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            CMP_SEARCH_2: [
                MessageHandler(filters.TEXT & ~filters.COMMAND, on_search_player2)
            ],
            CMP_PICK_2: [
                CallbackQueryHandler(on_pick_player2, pattern="^p2:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            SCATTER_COMPETITION: [
                CallbackQueryHandler(on_scatter_competition, pattern="^comp:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            SCATTER_POSITION: [
                CallbackQueryHandler(on_scatter_position, pattern="^pos:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            SCATTER_METRIC: [
                CallbackQueryHandler(on_scatter_metric, pattern="^smetric:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            SIMILAR_SEARCH: [
                MessageHandler(filters.TEXT & ~filters.COMMAND, on_search_similar)
            ],
            SIMILAR_PICK: [
                CallbackQueryHandler(on_pick_similar, pattern="^sim:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            TREND_TYPE: [
                CallbackQueryHandler(on_trend_type, pattern="^trendtype:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
            ],
            TREND_STAT: [
                CallbackQueryHandler(on_trend_stat_page, pattern="^statpage:"),
                CallbackQueryHandler(on_trend_stat, pattern="^stat:"),
                CallbackQueryHandler(on_back, pattern="^back:"),
                CallbackQueryHandler(noop, pattern="^noop$"),
            ],
        },
        fallbacks=[CommandHandler("cancel", cancel), CommandHandler("start", start)],
    )

    application.add_handler(conv_handler)
    application.add_handler(CommandHandler("help", help_command))
    return application


def main():
    """Regular entrypoint for `python telegram_bot.py` (plain script, no
    already-running event loop). Do NOT use this from a Colab/Jupyter cell —
    use run_in_notebook() instead, see below."""
    token = os.getenv("TELEGRAM_BOT_TOKEN")
    if not token:
        print("ERROR: set TELEGRAM_BOT_TOKEN environment variable.")
        return
    if data_processor is None:
        print(f"ERROR: data processor not initialized. Check FOOTBALL_CSV_PATH={CSV_PATH}")
        return

    application = build_application(token)
    print("Bot is starting...")
    application.run_polling(allowed_updates=Update.ALL_TYPES, stop_signals=None)


async def run_in_notebook(token: Optional[str] = None):
    """Colab/Jupyter-friendly entrypoint.

    `Application.run_polling()` is a blocking helper that tries to manage
    (and close) its own event loop — that clashes with the loop the notebook
    kernel already runs, producing "Cannot close a running event loop" when
    the cell is stopped. Calling the async pieces directly and awaiting them
    from a notebook cell (top-level `await` works in Colab/Jupyter) sidesteps
    that entirely.

    Usage in a Colab cell:
        from telegram_bot import run_in_notebook
        await run_in_notebook()          # reads TELEGRAM_BOT_TOKEN from env
        # or: await run_in_notebook("123456:ABC-your-token")

    Stop it with the cell's "Interrupt execution" (■) button — that raises
    KeyboardInterrupt, which is caught below and shuts the bot down cleanly.
    """
    token = token or os.getenv("TELEGRAM_BOT_TOKEN")
    if not token:
        print("ERROR: set TELEGRAM_BOT_TOKEN environment variable or pass token=...")
        return
    if data_processor is None:
        print(f"ERROR: data processor not initialized. Check FOOTBALL_CSV_PATH={CSV_PATH}")
        return

    application = build_application(token)
    print("Bot is starting (notebook mode)... interrupt the cell to stop it.")

    await application.initialize()
    await application.start()
    await application.updater.start_polling(allowed_updates=Update.ALL_TYPES)
    try:
        await asyncio.Event().wait()  # keep the coroutine alive until interrupted
    except (KeyboardInterrupt, asyncio.CancelledError):
        pass
    finally:
        print("Stopping bot...")
        await application.updater.stop()
        await application.stop()
        await application.shutdown()
        print("Bot stopped.")


